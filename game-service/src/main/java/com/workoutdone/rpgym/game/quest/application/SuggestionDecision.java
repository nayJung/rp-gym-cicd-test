package com.workoutdone.rpgym.game.quest.application;

import java.util.UUID;

// 유저가 제안을 수락하거나 거절했을 때의 결과다.
//
// 이 경로는 HTTP 요청이 부르므로 결과를 상태 코드로 바꿔야 하는데,
// 그렇다고 실패를 예외로 던지면 안 된다.
// 근거 스냅샷이 낡았을 때는 제안을 무효 상태로 바꾸면서 동시에 실패를 알려야 하는데,
// 예외를 던지면 트랜잭션이 롤백되면서 그 상태 변경이 사라진다.
// 그러면 다음 요청에서 또 같은 판정을 받고 또 롤백된다. 영원히 끝나지 않는다.
//
// 그래서 결과를 타입으로 돌려주고 컨트롤러가 상태 코드로 옮긴다.
// 판정 결과를 값으로 돌려주는 방식은 이 서비스가 원래 쓰던 방식이기도 하다.
// void 로 두면 무슨 일이 일어났는지 로그에서만 알 수 있고 테스트가 로그를 뒤져야 한다.
//
// sealed 라서 컨트롤러가 세 경우 중 하나를 빠뜨리면 컴파일이 실패한다.
public sealed interface SuggestionDecision {

    // 수락됐고 퀘스트가 만들어졌다. 응답에 그 퀘스트를 실어 보낸다.
    record Accepted(QuestView quest) implements SuggestionDecision {}

    // 거절됐다. 퀘스트는 만들어지지 않고 이벤트도 나가지 않는다.
    record Rejected(UUID suggestionId) implements SuggestionDecision {}

    record Failed(Reason reason) implements SuggestionDecision {}

    enum Reason {
        // 그런 제안이 없거나, 있지만 요청한 사람의 것이 아니다.
        // 남의 제안이라는 사실을 구분해서 알려주지 않는다.
        // 구분하는 순간 식별자를 하나씩 넣어보는 것만으로 남의 제안이 존재하는지 알 수 있다.
        NOT_FOUND,

        // 이미 수락했거나, 거절했거나, 무효가 된 제안이다.
        ALREADY_DECIDED,

        // 30분이 지났다.
        ALREADY_EXPIRED,

        // 이 제안이 근거한 스냅샷이 더 이상 최신이 아니다.
        // 제안과 수락 사이에 건강 데이터 동기화가 한 번 끼어들었다는 뜻이다.
        // 이대로 수락시키면 그 사이에 쌓인 활동이 baseline 밖으로 밀려나 소급 인정되고,
        // 목표가 작으면 수락하는 순간 완료되어 공짜로 XP 가 나간다.
        // 이 판정이 나면 제안을 무효 상태로 바꾼다.
        SUPERSEDED,

        // 이미 진행 중인 퀘스트가 있다.
        // 이때 제안은 대기 상태로 남긴다. 지금 퀘스트를 끝내고 다시 수락할 수 있어야 하기 때문이다.
        // 여기서 제안을 거절 상태로 만들면 유저가 고를 기회를 잃는다.
        QUEST_ALREADY_ACTIVE,

        // 이 유저의 건강 데이터 스냅샷이 하나도 저장돼 있지 않다.
        // 제안이 왔다는 것은 Health 가 동기화를 했다는 뜻이고,
        // 두 이벤트가 같은 토픽 같은 파티션으로 오므로 동기화가 먼저 도착했어야 한다.
        // 그러지 않았다면 계약이 깨진 것이라 사람이 봐야 한다.
        SNAPSHOT_MISSING,

        // 저장된 스냅샷의 활동 날짜가 제안의 활동 날짜와 다르다.
        // 자정 경계에서 자연히 생길 수 있다. 측정은 어제 23시 59분인데 제안은 0시 5분에 발행되어
        // 활동 날짜만 오늘로 찍히는 경우다.
        // 그대로 두면 baseline 이 어제 누적값이 되고, 오늘 누적값은 0부터 시작하므로
        // 달성분이 계속 음수가 되어 영원히 완료되지 않는다.
        // 다시 시도해도 결과가 같으므로 이 판정이 나면 제안을 무효 상태로 바꾼다.
        DATE_MISMATCH
    }
}
